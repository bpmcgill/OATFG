using OATFG.Core.DataModels;
using System.Collections.ObjectModel;

namespace OATFG.CSXUnitGenerator.DataModels
{
    public class Endpoint : IEndpoint
    {
        /// <summary>
        /// Theese are the responses for the endpoint.
        /// </summary>
        public ObservableCollection<Response>? CSXResponses { get; set; }

        /// <summary>
        /// This is the path for the endpoint. The property is used by the C# Framework and the Robot Framework.
        /// </summary>
        public string EndpointPath { get; set; }

        /// <summary>
        /// This is the name of the method that will be generated for the endpoint for the C# Framework.
        /// </summary>
        public string GeneratedMethodName { get; set; }

        /// <summary>
        /// This is the name of the private field that will be generated for the endpoint for the C# Framework.
        /// </summary>
        public string GeneratedPrivateFieldName { get; set; }

        /// <summary>
        /// This is the HTTP method used for the endpoint.
        /// </summary>
        public string Method { get; set; }

        /// <summary>
        /// This is the operation id for the endpoint. It comes from the swagger file, it has been generated by the developer. It may be used as an method name when there are collisions
        /// </summary>
        public string OperationId { get; set; }

        /// <summary>
        /// These are the path variables for the endpoint.
        /// </summary>
        public ObservableCollection<PathVariable>? PathVariables { get; set; }

        /// <summary>
        /// These are the query parameters for the endpoint.
        /// </summary>
        public ObservableCollection<QueryParameter>? QueryParameters { get; set; }

        /// <summary>
        /// This is the request body for the endpoint.
        /// </summary>
        public string? RequestBody { get; set; }

        /// <summary>
        /// This is the summary for the endpoint. It comes from the swagger file, it has been generated by the developer
        /// </summary>
        public string Summary { get; set; }
    }
}