using System.Collections.ObjectModel;

namespace OATFG.Core.DataModels
{
    public abstract class Endpoint : IEndpoint
    {
        /// <summary>
        /// This is the path for the endpoint. The property is used by the C# Framework and the Robot Framework.
        /// </summary>
        public string EndpointPath { get; set; }

        /// <summary>
        /// This is the HTTP method used for the endpoint.
        /// </summary>
        public string Method { get; set; }

        /// <summary>
        /// This is the operation id for the endpoint. It comes from the swagger file, it has been generated by the developer. It may be used as an method name when there are collisions
        /// </summary>
        public string OperationId { get; set; }

        /// <summary>
        /// These are the path variables for the endpoint. They are the same between the C# Framework and the Robot Framework.
        /// </summary>
        public ObservableCollection<string>? PathVariables { get; set; }

        /// <summary>
        /// These are the query variables for the endpoint. They are the same between the C# Framework and the Robot Framework.
        /// </summary>
        public ObservableCollection<string>? QueryVariables { get; set; }

        /// <summary>
        /// This is the request body for the endpoint. It is the same between the C# Framework and the Robot Framework.
        /// </summary>
        public string? RequestBody { get; set; }

        /// <summary>
        /// This is the response for the endpoint. It is the same between the C# Framework and the Robot Framework.
        /// </summary>
        public ObservableCollection<IResponse> Responses { get; set; }

        /// <summary>
        /// This is the summary for the endpoint. It comes from the swagger file, it has been generated by the developer
        /// </summary>
        public string Summary { get; set; }
    }
}